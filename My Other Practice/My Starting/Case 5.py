# Specific Data Type
strVar = str("Hello World - Richard") #Best Method
print(type(strVar)) #only type output

strVar2="Hello World - Richard"
print(type(strVar2))


#---------------------- int

intVar = int(50) #Best Method
print(type(intVar)) #only type output


intVar2=50
print(type(intVar2)) 



#---------------------- float

floatVar = float(50.3) #Best Method
print(type(floatVar)) #only type output


floatVar2=50.3
print(type(floatVar2))

