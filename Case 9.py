a= a + 5
a += 5
print ("a += 5 : ", a)
# Subtraction Assignment
a= a - 5
a -= 5
print ("a -= 5 : ", a)
# Multiplication Assignment
a = a * 5
a *= 5
print ("a *= 5 : ", a)
# Division Assignment
a = a /5
a /= 5
print ("a /= 5 : ",a)
# Remainder Assignment
a = a % 3
a %= 3
print ("a %= 3 : ", a)
# Exponent Assignment
a = a ** 2
a **= 2
print ("a **= 2 : ", a)
# Floor Division Assignment
a = a //3
a //= 3
print ("a //= 3 : ", a)